#!/usr/bin/env python3
import sys

code = bytes([
    0xB8, 0x04, 0x00,
    0xCD, 0x10,
    0x31, 0xF6,
    0x89, 0xF0,
    0x88, 0xC2,
    0x80, 0xE2, 0x1F,
    0x89, 0xF0,
    0xB1, 0x05,
    0xD3, 0xE8,
    0x88, 0xC6,
    0xB7, 0x00,
    0xB4, 0x02,
    0xCD, 0x10,
    0x89, 0xF0,
    0xB4, 0x09,
    0xBB, 0x03, 0x00,
    0xB9, 0x01, 0x00,
    0xCD, 0x10,
    0x46,
    0x81, 0xFE, 0x00, 0x01,
])
loop_start = 7
jb = bytes([0x72, (loop_start - (len(code) + 2)) & 0xFF])
tail = bytes([
    0x31, 0xC0, 0xCD, 0x16,
    0xB8, 0x03, 0x00, 0xCD, 0x10,
    0xCD, 0x20,
])
open(sys.argv[1], 'wb').write(code + jb + tail)
