import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { fileUse, OPTIONAL } from '../../game/byoc/convert/lists.js';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const args = process.argv.slice(2);
const opt = (k) => { const i = args.indexOf(k); return i < 0 ? null : args.splice(i, 2)[1]; };
const out = opt('--out') ?? here('../../docs/byoc/manifest.json');
const alts = [];
for (let d; (d = opt('--alt'));) alts.push(d.split('=', 2));
const check = args.includes('--check');
const dir = args.find((a) => !a.startsWith('--')) ?? '../re-targets/starcommand/starcoma';

const copy = here('../../game/byoc/import/manifest.json');
const sha = (b) => createHash('sha256').update(b).digest('hex');
const old = JSON.parse(readFileSync(copy, 'utf8')).list;
const kept = new Map(old.filter((f) => f.alt).map((f) => [f.name, f.alt])), saves = new Set(old.filter((f) => f.save).map((f) => f.name));
const files = [];
for (const name of readdirSync(dir).sort()) {
  if (!statSync(`${dir}/${name}`).isFile()) continue;
  const use = fileUse(name.toUpperCase());
  if (!use) throw new Error(`${name}: not a file of the known release (game/byoc/convert/lists.js)`);
  const bytes = readFileSync(`${dir}/${name}`);
  const row = { name: name.toUpperCase(), size: bytes.length, sha256: sha(bytes), use, required: use !== 'optional' };
  if (use === 'optional') row.note = OPTIONAL[row.name];
  const alt = [...(kept.get(row.name) ?? [])];
  for (const [ver, d] of alts) {
    if (!row.required || saves.has(row.name) || !existsSync(`${d}/${name}`)) continue;
    const b = readFileSync(`${d}/${name}`), a = { size: b.length, sha256: sha(b), ...(ver ? { ver } : {}) };
    if (a.sha256 !== row.sha256 && !alt.some((x) => x.sha256 === a.sha256)) alt.push(a);
  }
  if (alt.length) row.alt = alt;
  files.push(row);
}
const required = files.filter((f) => f.required);
const manifest = {
  release: 'Star Command (SSI, 1988), STARCOMA folder',
  version: 'starcoma-1',
  ver: '1.0',
  note: 'names, sizes and SHA-256 of the known release (alt = other accepted versions of a file); no file content. Generated by tools/byoc/make_manifest.mjs',
  files: files.length,
  required: required.length,
  bytes: files.reduce((n, f) => n + f.size, 0),
  list: files,
};
const { list, ...head } = manifest;
const render = (save) => `${JSON.stringify(head, null, 1).slice(0, -2)},\n "list": [\n${list.map(({ alt, ...f }) => `  ${JSON.stringify({ ...f, ...(save && saves.has(f.name) ? { save: true } : {}), ...(alt ? { alt } : {}) })}`).join(',\n')}\n ]\n}\n`;
const text = render(false), copyText = render(true);
if (check) {
  const ok = readFileSync(out, 'utf8') === text && readFileSync(copy, 'utf8') === copyText;
  console.log(ok ? `${out} + import copy match ${dir}` : `${out} or ${copy} differs from ${dir}`);
  process.exit(ok ? 0 : 1);
}
writeFileSync(out, text);
writeFileSync(copy, copyText);
console.log(`${files.length} files (${required.length} required, ${files.length - required.length} optional), ${manifest.bytes} bytes -> ${out}`);
