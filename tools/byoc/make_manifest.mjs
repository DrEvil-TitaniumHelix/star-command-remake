// make_manifest.mjs — docs/byoc/manifest.json from a Star Command folder (lane byoc-assets, docs/BYOC.md 3.1 step 2).
//
//   node tools/byoc/make_manifest.mjs [DIR] [--out FILE] [--check]
//   DIR default ../re-targets/starcommand/starcoma (read only)
//
// The manifest holds file names, sizes and SHA-256 hashes only (no content). `use` comes from
// game/byoc/convert/lists.js: module / runtime / data / bank are required, optional files may be missing.
// A file of DIR that lists.js does not know is an error (a new release needs its own manifest).
// Also written to game/byoc/import/manifest.json (identical copy, what the browser importer reads).
import { readdirSync, readFileSync, writeFileSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { fileUse, OPTIONAL } from '../../game/byoc/convert/lists.js';

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const args = process.argv.slice(2);
const opt = (k) => { const i = args.indexOf(k); return i < 0 ? null : args.splice(i, 2)[1]; };
const out = opt('--out') ?? here('../../docs/byoc/manifest.json');
const check = args.includes('--check');
const dir = args.find((a) => !a.startsWith('--')) ?? '../re-targets/starcommand/starcoma';

const files = [];
for (const name of readdirSync(dir).sort()) {
  if (!statSync(`${dir}/${name}`).isFile()) continue;
  const use = fileUse(name.toUpperCase());
  if (!use) throw new Error(`${name}: not a file of the known release (game/byoc/convert/lists.js)`);
  const bytes = readFileSync(`${dir}/${name}`);
  const row = { name: name.toUpperCase(), size: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex'), use, required: use !== 'optional' };
  if (use === 'optional') row.note = OPTIONAL[row.name];
  files.push(row);
}
const required = files.filter((f) => f.required);
const manifest = {
  release: 'Star Command (SSI, 1988), STARCOMA folder',
  version: 'starcoma-1',
  note: 'names, sizes and SHA-256 of the known release; no file content. Generated by tools/byoc/make_manifest.mjs',
  files: files.length,
  required: required.length,
  bytes: files.reduce((n, f) => n + f.size, 0),
  list: files,
};
const { list, ...head } = manifest;   // one file per line
const text = `${JSON.stringify(head, null, 1).slice(0, -2)},\n "list": [\n${list.map((f) => `  ${JSON.stringify(f)}`).join(',\n')}\n ]\n}\n`;
// the importer page fetches a copy next to it (tools/serve.py serves game/ only)
const copy = here('../../game/byoc/import/manifest.json');
if (check) {
  const ok = [out, copy].every((f) => readFileSync(f, 'utf8') === text);
  console.log(ok ? `${out} + import copy match ${dir}` : `${out} or ${copy} differs from ${dir}`);
  process.exit(ok ? 0 : 1);
}
writeFileSync(out, text);
writeFileSync(copy, text);
console.log(`${files.length} files (${required.length} required, ${files.length - required.length} optional), ${manifest.bytes} bytes -> ${out}`);
