def translate(mod, opt, text, names, const, sprites_text=None, originals=None):
    """-> {'js': module JS text, 'banks': banks.js text or None, 'log': [report lines]}"""
    if opt['backend'] == 'flow':
        be = FlowBackend(mod, opt, text, names, const)
        js = be.module_js()
        return {'js': js, 'banks': None, 'log': [be.stats]}
    be = ClassBackend(mod, opt, text, names, const, originals)
    regions = be.regions
    data = data_items(const)
    js = be.module_js(data)
    banks = bank_offsets(sprites_text)
    log = ['DATA items %d ; banks %d ; BLOAD regions %s' % (len(data), len(banks), {'%04X' % b: l for b, l in regions.items()}),
           'aliases %s' % be.ALIAS, '%d statements; %d untranslated' % (len(be.stmts), len(be.problems))]
    log += ['  %05X line %d: %s  <- %s' % p for p in be.problems[:60]]
    return {'js': js, 'banks': banks_js(banks, opt['tool_banner']), 'log': log}


