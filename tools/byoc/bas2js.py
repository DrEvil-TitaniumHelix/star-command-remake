"""bas2js.py — the one module translator: verified pseudocode (decode/pseudo/<MOD>.bas.md) -> module JS.
BYOC work item B3 step 1 (lane byoc-b3): merges the three former generators game/modules/{space,inside,starport}/bas2js.py
into one tool; the per-module differences are options in game/byoc/modules.json ("bas2js" of each module). The output is
byte-identical to what the three generators wrote (tools/byoc/rebuild_all.py checks it).

Two back ends (option "backend"):
- "class" (SPACE, INSIDE, PLBATTLE, SPBATTLE): a `class <Mod>Module extends <base>` whose `async exec(pc)` is one
  `for(;;) switch(pc)`; runs on game/modules/space/basic.js (BasicRT) or game/modules/inside/runtime.js (InsideRT).
  - each `L_xxxx:` / `SUB_xxxx:` label -> `case 0xXXXX:`; GOTO -> `pc = ...; continue`; GOSUB -> `await this.exec(target)`;
    RETURN -> `return`
  - FOR/NEXT paired by a pre-pass; the compiled test-at-top pattern is kept (zero-trip loops possible);
    an empty FOR..NEXT (busy delay loop) becomes `await this.delayLoop(count)` (BUILD_PLAN §2 timer.js)
  - backward jumps call `await this.tick()` so busy-wait loops (INKEY$ polling) yield to the frame scheduler
  - names: COMMON scalars/arrays -> G[] (Float32Array) / S(name) string arrays; arrays inside a BLOADed region
    -> 16-bit memory reads; everything else -> V[name] / A(name) (module-local, zero/"" initialised)
  Statements the translator cannot handle are emitted as `this.untranslated('<offset>', '<text>')` and reported.
- "flow" (STARPORT): `export async function flow(rt)` with an explicit GOSUB stack; helpers in game/modules/starport.js.
  GOTO L -> pc = L; continue;   GOSUB L -> gs.push(R); pc = L; continue; case R:   RETURN -> pc = gs.pop(); continue;
  FOR/NEXT: limit and step evaluated once at FOR, zero-trip test at FOR, increment + test at NEXT (paired by variable).
  Storage: COMMON singles -> G[n]; COMMON strings -> S.Name[i]; the INFO.BAS region (option "info") -> INFO[...];
  PUT/GET buffers (option "buffers") -> rt.put('Name', ...); everything else V.Name (! -> Name, % -> Name_i, $ -> Name_s).

Inputs (all paths explicit, defaults = the repo layout): the .bas.md, <MOD>_names.json, the modconst table _<MOD>.json
(DATA records, COMMON range), decode/data/sprites_index.tsv (banks.js), and the originals folder (the BSAVE length word
of the bank files a `BLOAD .., &H<base>` can load, for the class back end's memory views).

Usage (repo root): python -I tools/byoc/bas2js.py MOD [--src F] [--names F] [--const F] [--sprites F] [--originals DIR]
                                                    [--out F] [--banks-out F] [--config modules.json]
"""
import argparse, glob, json, os, re, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def split_top(s, seps=(',',)):
    """split at top-level separators (outside quotes/parentheses); returns [(piece, sep_after)]"""
    out, depth, q, cur = [], 0, False, ''
    for ch in s:
        if ch == '"': q = not q
        if not q:
            if ch == '(': depth += 1
            elif ch == ')': depth -= 1
            elif depth == 0 and ch in seps:
                out.append((cur, ch)); cur = ''; continue
        cur += ch
    out.append((cur, None))
    return out


def data_items(const):
    """DATA records of the module (modconst `data`, source order); READ splits items at commas and trims unquoted
    blanks like the BASIC READ parser"""
    items = []
    for r in const.get('data', []):
        if r.get('line') is None: continue      # terminator record
        for item, _ in split_top(r['text']):
            it = item.strip()
            items.append(it[1:-1] if it.startswith('"') and it.endswith('"') else it)
    return items


def bank_offsets(sprites_tsv_text):
    """array file offsets per sprite bank (decode/data/sprites_index.tsv), for PUT by DS address"""
    banks = {}
    for row in sprites_tsv_text.split('\n'):
        c = row.rstrip('\r\n').split('\t')
        if len(c) < 7: continue
        banks[c[0]] = [int(m.group(1)) for m in re.finditer(r'\d+:\d+x\d+@(\d+)', c[6])]
    return banks


def banks_js(banks, tool_banner):
    return ('// banks.js — GENERATED by %s from decode/data/sprites_index.tsv:\n'
            '// file offsets of the GET arrays in each sprite bank (index = position), used to PUT by DS address.\n'
            'export const BANK_OFFSETS = %s;\n' % (tool_banner, json.dumps(banks, separators=(',', ':'))))


def bsave_lengths(stmts, originals):
    """BLOAD regions (constant bases) for name resolution of memory arrays: base -> largest BSAVE length of the files
    that statement can load (read-only from the original files: header bytes 5..6). Returns {base: length}."""
    regions = {}
    for _, _, t, _ in stmts:
        m = re.search(r'^BLOAD (.*), &H([0-9A-F]+)$', t)
        if not m: continue
        base = int(m.group(2), 16)
        lits = [x for x in re.findall(r'"([^"]*)"', m.group(1)) if x not in ('A:', 'B:')]
        stem = lits[0].upper() if lits else ''
        ext = lits[-1].upper() if len(lits) > 1 and lits[-1].startswith('.') else ('' if '.' in stem else '.BAS')
        pat = os.path.join(originals, (stem + '*' + ext) if 'STR$' in m.group(1) else (stem + ext))
        ln = 0
        for f in glob.glob(pat):
            b = open(f, 'rb').read(7)
            if b[:1] == b'\xfd': ln = max(ln, struct.unpack_from('<H', b, 5)[0])
        regions[base] = max(regions.get(base, 0), ln)
    return regions


# ====================================================================== class back end (space, inside, plbattle, spbattle)
class ClassBackend:
    COMMON_LO, COMMON_HI = 0x1850, 0x40F4          # A()/G!() singles
    STR_LO, STR_HI = 0x4288, 0x4890                # COMMON string arrays (CROSSREF.md §2.4)
    TOK = re.compile(r'\s*(?:(&H[0-9A-Fa-f]+)|(\d+\.?\d*(?:[eE][+-]?\d+)?|\.\d+(?:[eE][+-]?\d+)?)|("[^"]*")|'
                     r'([A-Za-z_][A-Za-z0-9_]*[!%$#]?)|(<>|<=|>=|[-+*/\\^=<>(),;]))')
    KW = {'AND', 'OR', 'NOT', 'MOD', 'XOR', 'EQV', 'IMP'}
    FUNCS = {'CINT': 'cint', 'INT': 'Math.floor', 'ABS': 'Math.abs', 'SGN': 'sgn', 'SQR': 'Math.sqrt', 'LOG': 'Math.log',
             'EXP': 'Math.exp', 'SIN': 'Math.sin', 'COS': 'Math.cos', 'ATN': 'Math.atan', 'STR$': 'str', 'CHR$': 'chr',
             'ASC': 'asc', 'LEN': 'len', 'LEFT$': 'left', 'RIGHT$': 'right', 'MID$': 'mid', 'VAL': 'val',
             'STRING$': 'stringS', 'INSTR': 'instr', 'SPC': 'spc', 'POS': 'this.pos', 'RND': 'this.rnd',
             'FNCrew': 'this.FNCrew', 'FNIdx': 'this.FNIdx', 'FNRound2': 'this.FNRound2', 'FNKey': 'this.FNKey'}
    STRFUNCS = {'STR$', 'CHR$', 'LEFT$', 'RIGHT$', 'MID$', 'STRING$', 'INKEY$'}

    def __init__(self, mod, opt, text, names, const, originals):
        self.mod, self.opt, self.names, self.const = mod, opt, names, const
        self.lines = lines = text.split('\n')
        self.by_name = by_name = {}
        for k, v in names.items():
            if k.endswith('_why') or k.startswith(('_', 'SUB', 'FN')): continue
            if re.fullmatch(r'[0-9A-F]{4}', k): by_name.setdefault(v, ('s', int(k, 16)))
            elif re.fullmatch(r'A[0-9A-F]{4}', k): by_name.setdefault(v, ('a', int(k[1:], 16)))
        # scalars that ARE an element of a module array (same DS memory): the decode states `= Arr(n)` in the _why and
        # the address equals base + 4n (e.g. PLBATTLE SquadX! = GrpX!(5) at 0xC52C) -> both names share one storage
        self.ALIAS = ALIAS = {}
        arr_by_name = {v: int(k[1:], 16) for k, v in names.items() if re.fullmatch(r'A[0-9A-F]{4}', k)}
        for k, v in names.items():
            if not re.fullmatch(r'[0-9A-F]{4}', k): continue
            for mm in re.finditer(r'([A-Za-z_]\w*[!%$]?)\((\d+)\)', names.get(k + '_why', '')):
                an, n = mm.group(1), int(mm.group(2))
                if an != 'G!' and an in arr_by_name and arr_by_name[an] + 4 * n == int(k, 16): ALIAS[v] = (an, n)   # G! (COMMON) is already G[]
        # ... or listed per module where the _why does not spell the element out (option "alias_table"; address checked
        # against base + 4n; an address-only rule is unsafe: static arrays are not all 0..10, e.g. PLBATTLE
        # GrpAttackVerb! is followed by J!)
        addr_by_name = {v: int(k, 16) for k, v in names.items() if re.fullmatch(r'[0-9A-F]{4}', k)}
        for v, (an, n) in ((k, x) for k, x in opt.get('alias_table', {}).items() if not k.startswith('_')):
            if v not in addr_by_name: continue      # the decode now writes the element itself (crossref e11a94a: EnHeading!(5))
            if arr_by_name.get(an, -1) + 4 * n != addr_by_name.get(v): raise SystemExit('alias table: %s is not %s(%d) by address' % (v, an, n))
            ALIAS[v] = (an, n)
        # 2-D arrays: the module's Arrays table rows `2-D (first dimension N) | Name`
        self.TWO_D = {}
        for l in lines:
            m2 = re.match(r'^\| 0x[0-9A-F]+ \| [^|]*2-D \(first dimension (\d+)\) \| ([^|]+?) \|', l)
            if m2: self.TWO_D[m2.group(2).strip()] = int(m2.group(1))
        self.body = body = []
        inb = False
        for i, l in enumerate(lines, 1):
            if l.startswith('## Pseudocode'): inb = True; continue
            if inb and l.startswith('## '): break
            if not inb: continue
            m = re.match(r'^(L|SUB)_([0-9A-F]{4}):\s*$', l)
            if m: body.append(('label', int(m.group(2), 16), l)); continue
            m = re.match(r'^([0-9A-F]{5})  (.*)$', l)
            if m: body.append(('stmt', int(m.group(1), 16), m.group(2).rstrip(), i))
        self.stmts = stmts = [b for b in body if b[0] == 'stmt']
        self.regions = bsave_lengths(stmts, originals)
        self.bload_bases = sorted(self.regions)
        # FOR/NEXT pairing
        self.pair, stack = {}, []
        for idx, (_, off, t, ln) in enumerate(stmts):
            t = self.strip_comment(t)
            if t.startswith('FOR '): stack.append(idx)
            elif t.startswith('NEXT'):
                if not stack: continue
                f = stack.pop(); self.pair[f] = idx; self.pair[idx] = f
        # DEF FNs. Option "fn_inline": the module's FN bodies as JS templates expanded at each call ({0}, {1} = the
        # arguments; {"ref": Name, "idx": template} = an element of a module array). Otherwise every names.json
        # `FN<addr>` (+ `_args` DS addresses) becomes a method whose body is the `RETURN 'with FAC = <expr>` line.
        self.fn_inline = {k: v for k, v in opt.get('fn_inline', {}).items() if not k.startswith('_')}
        self.fn_defs = []
        if not self.fn_inline:
            addr2name = {k: v for k, v in names.items() if re.fullmatch(r'[0-9A-F]{4}', k)}
            for k, v in names.items():
                m3 = re.fullmatch(r'FN([0-9A-F]{4})', k)
                if not m3: continue
                args = [addr2name.get(a.strip(), 'N_%s!' % a.strip()) for a in names.get(k + '_args', '').split(',') if a.strip()]
                bodyline = None
                for i2, l in enumerate(lines):
                    if l.strip() == 'SUB_%s:' % m3.group(1):
                        for l2 in lines[i2 + 1:i2 + 4]:
                            mb = re.match(r"^[0-9A-F]{5}  RETURN\s+'with FAC = (.*)$", l2)
                            if mb: bodyline = mb.group(1); break
                        break
                self.fn_defs.append((v, args, bodyline, m3.group(1)))
        self.FN_NAMES = {n for n, *_ in self.fn_defs}
        self.problems = []

    @staticmethod
    def strip_comment(t):
        out, q = [], False
        for ch in t:
            if ch == '"': q = not q
            if ch == "'" and not q: return ''.join(out).rstrip()
            out.append(ch)
        return ''.join(out).rstrip()

    # ------------------------------------------------------------------ expressions
    def tokens(self, s):
        t = []; pos = 0
        while pos < len(s):
            m = self.TOK.match(s, pos)
            if not m or m.end() == pos:
                if s[pos:].strip() == '': break
                raise SyntaxError('tok@%d %r' % (pos, s[pos:pos + 15]))
            pos = m.end()
            hx, num, st, idn, op = m.groups()
            if hx: t.append(('num', str(int(hx[2:], 16))))
            elif num: t.append(('num', num))
            elif st: t.append(('str', st))
            elif idn: t.append(('kw', idn.upper()) if idn.upper() in self.KW else ('id', idn))
            else: t.append(('op', op))
        return t

    def expr(self, s):
        p = _Expr(self, self.tokens(s)); e = p.parse()
        if not p.done(): raise SyntaxError('trailing %r' % (p.t[p.i:],))
        return e

    def fn_call(self, v, a):
        tpl = self.fn_inline[v]
        sub = lambda s: s.replace('{0}', a[0] if len(a) > 0 else '').replace('{1}', a[1] if len(a) > 1 else '')
        if isinstance(tpl, dict): return (self.ref(tpl['ref'], [sub(tpl['idx'])]), 'n')
        return (sub(tpl), 'n')

    def in_region(self, a):
        return any(b <= a < b + self.regions[b] for b in self.bload_bases)

    def ref(self, name, idx):
        """JS lvalue/rvalue for a BASIC variable or array element"""
        if idx is None and name in self.ALIAS: return 'A(%s)[%d]' % (json.dumps(self.ALIAS[name][0]), self.ALIAS[name][1])
        if name == 'G!' and idx is not None: return 'G[cint(%s)]' % idx[0]
        info = self.by_name.get(name)
        if idx is None:
            if info and info[0] == 's' and self.COMMON_LO <= info[1] < self.COMMON_HI:
                return 'G[%d]' % ((info[1] - self.COMMON_LO) // 4)
            if info and info[0] == 's' and self.STR_LO <= info[1] < self.STR_HI:      # COMMON string scalar (ShipName$)
                return 'S(%s)[0]' % json.dumps(name)
            # an integer scalar inside a BLOADed region is a word of the loaded file (PLBATTLE FrameDX1%..FrameDY3% =
            # the overlay offsets stored in BIGSH-n.EGA at &H8052 +2468..+2478): read/write it through memory
            if info and info[0] == 's' and name.endswith('%') and self.in_region(info[1]):
                return 'M16(0x%04X, 0)' % info[1]
            return 'V[%s]' % json.dumps(name)
        TWO_D = self.TWO_D
        ix = 'cint(%s)' % idx[0] if len(idx) == 1 else 'cint(%s) + %d * cint(%s)' % (idx[0], TWO_D.get(name, 0) or 0, idx[1])
        if len(idx) == 2 and name not in TWO_D: raise SyntaxError('2-D array without dims: ' + name)
        if info and info[0] == 'a':
            base = info[1]
            if self.COMMON_LO <= base < self.COMMON_HI: return 'G[%d + %s]' % ((base - self.COMMON_LO) // 4, ix)
            if self.STR_LO <= base < self.STR_HI and name.endswith('$'): return 'S(%s)[%s]' % (json.dumps(name), ix)
            if self.in_region(base) and not name.endswith(('$', '!', '#')):
                return 'M16(0x%04X, %s)' % (base, ix)      # integer word view of BLOADed memory
        return 'A(%s)[%s]' % (json.dumps(name), ix)

    def assign(self, target, valjs):
        m = re.match(r'^([A-Za-z_][\w]*[!%$#]?)\s*(\((.*)\))?$', target.strip())
        if not m: raise SyntaxError('target %r' % target)
        name, _, ix = m.groups()
        idx = None
        if ix is not None: idx = [self.expr(a)[0] for a, _ in split_top(ix)]
        lv = self.ref(name, idx)
        if lv.startswith('M16('): return 'W16(%s, %s);' % (lv[4:-1], valjs)
        if name.endswith('%'): return '%s = cint(%s);' % (lv, valjs)
        if name.endswith('$'): return '%s = %s;' % (lv, valjs)
        return '%s = fr(%s);' % (lv, valjs)

    def pt(self, s):  # "(x, y)" -> "x, y"
        s = s.strip(); assert s[0] == '(' and s[-1] == ')', s
        a = split_top(s[1:-1]); assert len(a) == 2, s
        return '%s, %s' % (self.expr(a[0][0])[0], self.expr(a[1][0])[0])

    @staticmethod
    def lbl(name): return '0x%s' % name.split('_')[1]
    @staticmethod
    def syn(off, k): return '0x%X' % (0x100000 + 2 * off + k)

    # ------------------------------------------------------------------ statements
    def tr(self, idx, off, t):
        expr, assign, pt, lbl, syn, ref, opt = self.expr, self.assign, self.pt, self.lbl, self.syn, self.ref, self.opt
        t0 = t; t = self.strip_comment(t)
        if not t: return '// ' + t0
        if re.match(r'^-?\d+(\.\d+)? = ', t): return '// (data after the last RETURN, not a statement) ' + t0
        if t.startswith('GOTO '):
            tgt = lbl(t.split()[1]); back = int(tgt, 16) <= off
            return ('await this.tick(); ' if back else '') + 'pc = %s; continue;' % tgt
        if t.startswith('GOSUB '): return 'await this.exec(%s);' % lbl(t.split()[1])
        if t.startswith('RETURN'): return 'return;'
        m = re.match(r'^IF (.*) THEN GOTO ((?:L|SUB)_[0-9A-F]{4})$', t)
        if m:
            tgt = lbl(m.group(2)); back = int(tgt, 16) <= off
            return 'if (%s !== 0) { %spc = %s; continue; }' % (expr(m.group(1))[0], 'await this.tick(); ' if back else '', tgt)
        m = re.match(r'^ON (.*) (GOTO|GOSUB) (.*)$', t)
        if m:
            tg = '[%s]' % ', '.join(lbl(x.strip()) for x in m.group(3).split(','))
            if m.group(2) == 'GOSUB': return '{ const t = %s[cint(%s) - 1]; if (t !== undefined) await this.exec(t); }' % (tg, expr(m.group(1))[0])
            return '{ const t = %s[cint(%s) - 1]; if (t !== undefined) { await this.tick(); pc = t; continue; } }' % (tg, expr(m.group(1))[0])
        m = re.match(r'^FOR (\S+) = (.*) TO (.*)$', t)
        if m:
            var, a, b = m.groups(); ni = self.pair.get(idx)
            if ni is None: raise SyntaxError('FOR without NEXT')
            nt = self.strip_comment(self.stmts[ni][2]); sm = re.match(r'^NEXT \S+ STEP (.*)$', nt)
            step = expr(sm.group(1))[0] if sm else '1'
            lv = ref(var, None); key = '0x%05X' % off
            if ni == idx + 1:   # empty body = busy delay loop
                return '%s = fr(%s); await this.delayLoop(this.forCount(%s, %s, %s)); %s = fr(this.forEnd(%s, %s, %s)); pc = %s; continue;' % (
                    lv, expr(a)[0], lv, expr(b)[0], step, lv, lv, expr(b)[0], step, syn(self.stmts[ni][1], 0))
            return ('%s = fr(%s); this.F[%s] = %s; if (!this.forOk(%s, this.F[%s], %s)) { pc = %s; continue; }\n      case %s:' %
                    (lv, expr(a)[0], key, expr(b)[0], lv, key, step, syn(self.stmts[ni][1], 0), syn(off, 1)))
        m = re.match(r'^NEXT (\S+)(?: STEP (.*))?$', t)
        if m:
            fi = self.pair.get(idx)
            if fi is None: raise SyntaxError('NEXT without FOR')
            if fi == idx - 1: return '// (delay loop end)\n      case %s:' % syn(off, 0)
            lv = ref(m.group(1), None); step = expr(m.group(2))[0] if m.group(2) else '1'
            return ('%s = fr(%s + %s); if (this.forOk(%s, this.F[0x%05X], %s)) { await this.tick(); pc = %s; continue; }\n      case %s:' %
                    (lv, lv, step, lv, self.stmts[fi][1], step, syn(self.stmts[fi][1], 1), syn(off, 0)))
        if t.startswith('PRINT USING '):
            parts = split_top(t[12:], (';', ','))
            fmt = expr(parts[0][0])[0]; parts = parts[1:]
            items = [expr(x)[0] for x, _ in parts if x.strip()]
            semi = parts[-1][0].strip() == ''
            return 'this.printUsing(%s, [%s], %s);' % (fmt, ', '.join(items), 'true' if semi else 'false')
        if t == 'PRINT' or t.startswith('PRINT '):
            rest = t[5:].strip(); out = []; groups = []
            for x, sep in split_top(rest, (';', ',')):
                g = []
                if x.strip(): g.append(expr(x)[0])
                if sep: g.append('SEMI' if sep == ';' else 'COMMA')
                groups.append(g); out += g
            # BASIC prints each item before it evaluates the next: an item that reads the cursor (POS(0), CSRLIN) after
            # an earlier one must see the cursor moved, so such a PRINT is emitted one item at a time (option
            # print_whole: not done, the INSIDE generator never had this rule)
            if not opt.get('print_whole') and any(('this.pos(' in i or 'this.csrlin(' in i) for g in groups[1:] for i in g):
                return ' '.join('this.print([%s]);' % ', '.join(g) for g in groups if g)
            return 'this.print([%s]);' % ', '.join(out)
        m = re.match(r'^LOCATE ?(.*)$', t)
        if m:
            a = split_top(m.group(1))
            r = expr(a[0][0])[0] if a[0][0].strip() else 'null'
            c = expr(a[1][0])[0] if len(a) > 1 and a[1][0].strip() else 'null'
            if opt.get('locate_cursor'):      # LOCATE r, c, cursor, start, stop -> this.cursor() (INSIDE line editor SUB_157D 015C0)
                if len(a) > 2:
                    cur = [expr(x[0])[0] if x[0].strip() else 'undefined' for x in a[2:5]]
                    return 'this.locate(%s, %s); this.cursor(%s);' % (r, c, ', '.join(cur))
                return 'this.locate(%s, %s);' % (r, c)
            extra = [expr(x)[0] if x.strip() else 'undefined' for x, _ in a[2:]]
            return 'this.locate(%s, %s%s);' % (r, c, (', ' + ', '.join(extra)) if extra else '')
        m = re.match(r'^PUT (\([^()]*(?:\([^()]*\)[^()]*)*\)), ([A-Za-z_]\w*[!%$]?)(?:\(([^)]*)\))?, (\w+)$', t)
        if m:
            name = m.group(2); info = self.by_name.get(name)
            addr = '0x%04X' % info[1] if info else 'null'
            return 'this.put(%s, %s, %s, %s);' % (pt(m.group(1)), json.dumps(name), addr, json.dumps(m.group(4)))
        m = re.match(r'^GET (\(.*?\))-(\(.*?\)), ([A-Za-z_]\w*[!%$]?)$', t)
        if m: return 'this.get(%s, %s, %s);' % (pt(m.group(1)), pt(m.group(2)), json.dumps(m.group(3)))
        m = re.match(r'^LINE (\(.*?\))-(\(.*?\))(.*)$', t)
        if m:
            rest = m.group(3)      # like ", 1, BF" or ", , B" or ", 2"
