class _Expr:
    """class back end expressions: recursive descent with QuickBASIC precedence; returns (js, type) type in {'n','s'}"""
    def __init__(self, be, toks): self.be, self.t, self.i = be, toks, 0
    def peek(self, k=0): return self.t[self.i + k] if self.i + k < len(self.t) else (None, None)
    def take(self): x = self.peek(); self.i += 1; return x
    def expect(self, v):
        x = self.take()
        if x[1] != v: raise SyntaxError('expected %s got %r' % (v, x))
    def done(self): return self.i >= len(self.t)
    def parse(self): return self.xor_()
    def bin(self, nxt, ops, fn):
        a = nxt()
        while self.peek()[1] in ops:
            op = self.take()[1]; b = nxt(); a = fn(op, a, b)
        return a
    def xor_(self): return self.bin(self.or_, ('XOR',), lambda o, a, b: ('(cint(%s) ^ cint(%s))' % (a[0], b[0]), 'n'))
    def or_(self): return self.bin(self.and_, ('OR',), lambda o, a, b: ('(cint(%s) | cint(%s))' % (a[0], b[0]), 'n'))
    def and_(self): return self.bin(self.not_, ('AND',), lambda o, a, b: ('(cint(%s) & cint(%s))' % (a[0], b[0]), 'n'))
    def not_(self):
        if self.peek()[1] == 'NOT':
            self.take(); a = self.not_(); return ('(~cint(%s))' % a[0], 'n')
        return self.cmp()
    def cmp(self):
        a = self.add()
        CM = {'=': 'eq', '<>': 'ne', '<': 'lt', '>': 'gt', '<=': 'le', '>=': 'ge'}
        while self.peek()[1] in CM:
            op = self.take()[1]; b = self.add()
            a = ('%s(%s, %s)' % (CM[op], a[0], b[0]), 'n')
        return a
    def add(self):
        a = self.mod()
        while self.peek()[1] in ('+', '-'):
            op = self.take()[1]; b = self.mod()
            t = 's' if (a[1] == 's' or b[1] == 's') else 'n'
            a = ('(%s %s %s)' % (a[0], op, b[0]), t)
        return a
    def mod(self): return self.bin(self.idiv, ('MOD',), lambda o, a, b: ('mod(%s, %s)' % (a[0], b[0]), 'n'))
    def idiv(self): return self.bin(self.mul, ('\\',), lambda o, a, b: ('idiv(%s, %s)' % (a[0], b[0]), 'n'))
    def mul(self): return self.bin(self.neg, ('*', '/'), lambda o, a, b: ('(%s %s %s)' % (a[0], o, b[0]), 'n'))
    def neg(self):
        if self.peek()[1] == '-':
            self.take(); a = self.neg(); return ('(-%s)' % a[0], 'n')
        if self.peek()[1] == '+':
            self.take(); return self.neg()
        return self.pow()
    def pow(self):
        a = self.atom()
        while self.peek()[1] == '^':
            self.take(); b = self.neg()
            a = ('Math.pow(%s, %s)' % (a[0], b[0]), 'n')
        return a
    def args(self):
        out = []
        if self.peek()[1] != '(': return out
        self.take()
        if self.peek()[1] == ')': self.take(); return out
        while True:
            out.append(self.parse())
            x = self.take()
            if x[1] == ')': return out
            if x[1] != ',': raise SyntaxError('args %r' % (x,))
    def atom(self):
        be = self.be
        k, v = self.take()
        if k == 'num': return (v, 'n')
        if k == 'str': return (v, 's')
        if k == 'op' and v == '(':
            e = self.parse(); self.expect(')'); return ('(%s)' % e[0], e[1])
        if k == 'id':
            U = v.upper()
            if U == 'INKEY$': return ('this.inkey()', 's')
            if U == 'TIMER': return ('this.timerNow()', 'n')
            if U == 'CSRLIN': return ('this.csrlin()', 'n')
            if U == 'RND' and self.peek()[1] != '(': return ('this.rnd()', 'n')
            if v in be.fn_inline:
                return be.fn_call(v, [x[0] for x in self.args()])
            if U == 'EOF': a = self.args(); return ('this.eof(%s)' % a[0][0], 'n')
            if v in be.FN_NAMES:
                a = self.args(); return ('this.%s(%s)' % (v, ', '.join(x[0] for x in a)), 's' if v.endswith('$') else 'n')
            if U in be.FUNCS or v in be.FUNCS:
                f = be.FUNCS.get(U, be.FUNCS.get(v)); a = self.args()
                js = '%s(%s)' % (f, ', '.join(x[0] for x in a))
                return (js, 's' if U in be.STRFUNCS else 'n')
            if self.peek()[1] == '(':
                a = self.args(); return (be.ref(v, [x[0] for x in a]), 's' if v.endswith('$') else 'n')
            return (be.ref(v, None), 's' if v.endswith('$') else 'n')
        raise SyntaxError('atom %r' % ((k, v),))


# ====================================================================== flow back end (starport)
class FlowBackend:
    TOK = re.compile(r'\s*(?:(&H[0-9A-Fa-f]+)|(\d+\.\d*|\.\d+|\d+)|("[^"]*")|([A-Za-z][A-Za-z0-9_]*[!%$]?)|(<>|<=|>=|[-+*/\\^=<>(),;?]))')
    FUNCS = {'CINT', 'INT', 'ABS', 'LEN', 'LEFT$', 'RIGHT$', 'MID$', 'CHR$', 'ASC', 'STR$', 'VAL', 'SPC', 'SPACE$',
             'STRING$', 'POS', 'SGN', 'FNCrew', 'FNIdx', 'FNCredits', 'VARPTR$'}
    NOARG = {'RND': 'rt.rnd()', 'TIMER': 'rt.TIMER()', 'INKEY$': 'rt.inkey()', 'CSRLIN': 'rt.csrlin()'}
    FUNC_JS = {'CINT': 'cint({0})', 'INT': 'Math.floor({0})', 'ABS': 'Math.abs({0})', 'LEN': '({0}).length',
               'CHR$': 'String.fromCharCode(cint({0}))', 'ASC': 'ASC({0})', 'STR$': 'STR({0})', 'VAL': 'VAL({0})',
               'SPC': "' '.repeat(cint({0}))", 'SPACE$': "' '.repeat(cint({0}))", 'SGN': 'Math.sign({0})',
               'POS': 'rt.pos()', 'VARPTR$': '{0}',
               'LEFT$': 'LEFT({0}, {1})', 'RIGHT$': 'RIGHT({0}, {1})', 'STRING$': 'STRING({0}, {1})',
               'FNCredits': 'FNCredits()'}

    def __init__(self, mod, opt, text, names, const):
        self.mod, self.opt, self.text = mod, opt, text
        self.COMMON_BASE, self.COMMON_LEN = 0x1850, 10404    # G!() = 2601 singles
        self.CSTR_LO, self.CSTR_HI = 0x4288, 0x4890
        self.INFO_BASE = int(opt['info']['base'], 16); self.INFO_END = self.INFO_BASE + opt['info']['bytes']
        self.BUFFERS = set(opt['buffers'])
        self.TWO_D = opt.get('two_d', {})
        self.scalar_addr, self.array_addr = {}, {}
        for k, v in names.items():
            if k.startswith('_') or k.endswith(('_why', '_args', '_count')) or k.startswith(('SUB', 'FN')) or not isinstance(v, str):
                continue      # A<base>_count = array extent (sweep-folded d76e346)
            if '(' in v:          # fixed elements like "G!(16)", "AttrName$(0)" - rendered as array refs
                continue
            # key format: 'A' + 4 hex digits = array at that DS address; 4 hex digits = scalar (e.g. AA2C Flag!, A4E4 PortNo!)
            if re.fullmatch(r'A[0-9A-F]{4}', k):
                self.array_addr[v] = int(k[1:], 16)
            elif re.fullmatch(r'[0-9A-F]{3,4}', k):
                self.scalar_addr[v] = int(k, 16)

    @staticmethod
    def jsname(n):
        base = n[:-1] if n[-1] in '!%$' else n
        suf = {'!': '', '%': '_i', '$': '_s'}.get(n[-1], '')
        return re.sub(r'\W', '_', base) + suf

    def scalar_ref(self, n):
        a = self.scalar_addr.get(n)
        if a is not None and self.COMMON_BASE <= a < self.COMMON_BASE + self.COMMON_LEN and n[-1] != '$':
            return f'G[{(a - self.COMMON_BASE) // 4}]'
        if a is not None and self.CSTR_LO <= a < self.CSTR_HI + 4 and n[-1] == '$':
            return f'S.{self.jsname(n)[:-2]}[0]'        # ShipName$ (COMMON string scalar)
        return f'V.{self.jsname(n)}'

    def array_ref(self, n, idx_js):
        """idx_js: list of JS index expressions"""
        if n == 'G!':
            return f'G[ix({idx_js[0]})]'
        a = self.array_addr.get(n)
        if a is not None and self.INFO_BASE <= a < self.INFO_END:
            off = (a - self.INFO_BASE) // 4
            if n in self.TWO_D:
                return f'INFO[{off} + ix({idx_js[0]}) + {self.TWO_D[n]} * ix({idx_js[1]})]'
            return f'INFO[{off} + ix({idx_js[0]})]'
        if a is not None and self.CSTR_LO <= a < self.CSTR_HI and n[-1] == '$':
            return f'S.{self.jsname(n)[:-2]}[ix({idx_js[0]})]'
        if len(idx_js) != 1:
            raise SystemExit(f'unexpected multi-dim local array {n}')
        return f'A.{self.jsname(n)}[ix({idx_js[0]})]'

    def tokenize(self, s):
        out, i = [], 0
        s = s.rstrip()
        while i < len(s):
            m = self.TOK.match(s, i)
            if not m or m.end() == i:
                if s[i:].strip() == '':
                    break
                raise SyntaxError(f'tokenize at {s[i:]!r} in {s!r}')
            i = m.end()
            h, num, st, ident, op = m.groups()
            if h: out.append(('num', str(int(h[2:], 16))))
            elif num: out.append(('num', num))
            elif st: out.append(('str', st))
            elif ident:
                up = ident.upper()
                if up in ('AND', 'OR', 'NOT', 'MOD', 'XOR'): out.append(('op', up))
                else: out.append(('id', ident))
            else: out.append(('op', op))
        return out

    def func(self, name, a):
        n = name.upper()
        if n == 'MID$':
            return f'MID({a[0]}, {a[1]}' + (f', {a[2]})' if len(a) > 2 else ')')
        if n == 'FNCREW': return f'FNCrew({a[0]}, {a[1]})'
        if n == 'FNIDX': return f'FNIdx({a[0]}, {a[1]})'
        if n == 'FNCREDITS': return 'FNCredits()'
        return self.FUNC_JS[n].format(*a)

    def E(self, s):
        p = _FlowP(self, self.tokenize(s)); e = p.expr()
        if not p.done(): raise SyntaxError(f'trailing tokens in {s!r}: {p.t[p.i:]}')
        return e

    def lvalue(self, s):
        p = _FlowP(self, self.tokenize(s)); kind, v = p.take()
        if kind != 'id': raise SyntaxError(s)
        if p.at('('):
            r = self.array_ref(v, p.args())
        else:
            r = self.scalar_ref(v)
        if not p.done(): raise SyntaxError(f'lvalue {s}')
        return r, v[-1]

    def assign(self, lhs, rhs_js):
        r, suf = self.lvalue(lhs)
        if r.startswith('G[') or r.startswith('INFO['): return f'{r} = {rhs_js};'   # Float32Array: single rounding
        if suf == '%': return f'{r} = cint({rhs_js});'
        if suf == '$': return f'{r} = {rhs_js};'
        return f'{r} = fr({rhs_js});'

    @staticmethod
    def lab(name):
        m = re.fullmatch(r'(?:L|SUB)_([0-9A-F]+)', name.strip())
        if not m: raise SyntaxError(f'label {name}')
        return int(m.group(1), 16)

    def print_items(self, body, fn):
        parts = split_top(body, ';,')
        js = []
        for p, sep in parts:
            p = p.strip()
            if p:
                js.append(f'{fn}({self.E(p)});')
            if sep == ',':
                js.append(f'{fn}Zone();')
        last_sep = parts[-1][0].strip() == '' and len(parts) > 1
        js.append(f'{fn}End({"true" if last_sep else "false"});')
        return [' '.join(js)]

    def stmt(self, off, s, ctx):
        """returns list of JS lines (without the comment)"""
        E, lab, assign, lvalue = self.E, self.lab, self.assign, self.lvalue
        S_ = s.strip()
        for a, b in self.opt.get('text_fixes', []):     # see the option's _why in modules.json
            S_ = S_.replace(a, b)
        u = S_.upper()
        nxt = ctx['next_ret']
        if re.match(r"(RETURN|END)( |$)", S_):
            S_ = S_.split()[0]; u = S_
        if S_.startswith("'") or S_ == 'N(?) = 0':
            return ['// (not code: listing data bytes)']
        if u == 'RETURN':
            return ['pc = gs.pop(); continue;']
        if u == 'END':
            return ['return rt.end();']
        m = re.fullmatch(r'GOTO (\w+)', S_)
        if m: return [f'pc = 0x{lab(m.group(1)):04X}; continue;']
        m = re.fullmatch(r'GOSUB (\w+)', S_)
        if m:
            t = lab(m.group(1))
            if t not in ctx['labels']:
                return [f'throw new Error("GOSUB to non-existent SUB_{t:04X} (phantom, see {self.mod}.bas.md Manual corrections)");']
            r = nxt()
            return [f'gs.push({r}); pc = 0x{t:04X}; continue;', f'case {r}:']
        m = re.fullmatch(r'IF (.*) THEN GOTO (\w+)', S_)
        if m: return [f'if ({E(m.group(1))}) {{ pc = 0x{lab(m.group(2)):04X}; continue; }}']
        m = re.fullmatch(r'ON (.*) (GOTO|GOSUB) ([\w, ]+)', S_)
        if m:
            tg = ', '.join(f'0x{lab(x):04X}' for x in m.group(3).split(','))
            n = len(m.group(3).split(','))
            if m.group(2) == 'GOTO':
                return [f'{{ const k = cint({E(m.group(1))}); if (k >= 1 && k <= {n}) {{ pc = [{tg}][k - 1]; continue; }} }}']
            r = nxt()
            return [f'{{ const k = cint({E(m.group(1))}); if (k >= 1 && k <= {n}) {{ gs.push({r}); pc = [{tg}][k - 1]; continue; }} }}',
                    f'case {r}:']
        m = re.fullmatch(r'FOR (\S+) = (.*) TO (.*)', S_)
        if m:
            return ctx['for'](off, m.group(1), m.group(2), m.group(3))
        m = re.fullmatch(r'NEXT (\S+)(?: STEP (.*))?', S_)
        if m:
            return ctx['next'](off, m.group(1))
        m = re.fullmatch(r'LOCATE (.*)', S_)
        if m:
            parts = [p.strip() for p, _ in split_top(m.group(1), ',')]
            js = [E(p) if p else 'undefined' for p in parts]
            return [f'rt.locate({", ".join(js)});']
        m = re.fullmatch(r'PRINT #1, (.*)', S_)
        if m:
            return self.print_items(m.group(1), 'rt.fprint')
        m = re.fullmatch(r'PRINT USING (.*?); (.*?)(;?)', S_)
        if m:
            return [f'rt.printUsing({E(m.group(1))}, {E(m.group(2))}, {"true" if m.group(3) else "false"});']
        if u == 'PRINT':
            return ['rt.printEnd(false);']
        m = re.fullmatch(r'PRINT (.*)', S_)
        if m:
            return self.print_items(m.group(1), 'rt.print')
        m = re.fullmatch(r'INPUT #1, (.*)', S_)
        if m:
            return [assign(v.strip(), f'await rt.finput({"true" if v.strip().split("(")[0].endswith("$") else "false"})')
                    for v, _ in split_top(m.group(1), ',')]
        m = re.fullmatch(r'INPUT (".*"); (.*)', S_)
        if m:
            return [assign(m.group(2), f'await rt.inputNum({m.group(1)})')]
        m = re.fullmatch(r'OPEN (.*) FOR (INPUT|OUTPUT) AS #1', S_)
        if m: return [f'await rt.open({E(m.group(1))}, "{m.group(2)}");']
        if u == 'CLOSE #1': return ['await rt.close();']
        m = re.fullmatch(r'BLOAD (.*), (&H[0-9A-F]+)', S_)
        if m: return [f'await rt.bload({E(m.group(1))}, 0x{m.group(2)[2:]});']
        m = re.fullmatch(r'BSAVE (.*), (&H[0-9A-F]+), (\d+)', S_)
        if m: return [f'await rt.bsave({E(m.group(1))}, 0x{m.group(2)[2:]}, {m.group(3)});']
        m = re.fullmatch(r'CHAIN (.*)', S_)
        if m: return [f'return rt.chain({E(m.group(1))});']
        m = re.fullmatch(r'LINE \((.*?), (.*?)\)-\((.*?), (.*?)\)(?:, (.*?))?(?:, (BF|B))?', S_)
        if m:
            x1, y1, x2, y2, c, b = m.groups()
            c = E(c) if c and c.strip() else 'undefined'
            return [f'rt.line({E(x1)}, {E(y1)}, {E(x2)}, {E(y2)}, {c}, {json.dumps(b or "")});']
        m = re.fullmatch(r'(PSET|PRESET) \((.*?), (.*?)\)', S_)
        if m: return [f'rt.{m.group(1).lower()}({E(m.group(2))}, {E(m.group(3))});']
        m = re.fullmatch(r'PUT \((.*?), (.*?)\), (\w+), (\w+)', S_)
        if m:
            assert m.group(3) in self.BUFFERS, m.group(3)
            return [f'rt.put({E(m.group(1))}, {E(m.group(2))}, "{m.group(3)}", "{m.group(4)}");']
        m = re.fullmatch(r'GET \((.*?), (.*?)\)-\((.*?), (.*?)\), (\w+)', S_)
        if m:
            return [f'rt.get({E(m.group(1))}, {E(m.group(2))}, {E(m.group(3))}, {E(m.group(4))}, "{m.group(5)}");']
        if u == 'CLS': return ['rt.cls();']
        if u == 'KEY OFF': return ['rt.keyOff();']
        if u == 'BEEP': return ['await rt.beep();']
        m = re.fullmatch(r'SCREEN (\d+)', S_)
        if m: return [f'rt.screen({m.group(1)});']
        m = re.fullmatch(r'PALETTE (\d+), (\d+)', S_)
        if m: return [f'rt.palette({m.group(1)}, {m.group(2)});']
        m = re.fullmatch(r'SOUND (.*)', S_)
        if m:
            a = [E(p) for p, _ in split_top(m.group(1), ',')]
            return [f'await rt.sound({a[0]}, {a[1]});']
        m = re.fullmatch(r'PLAY (.*)', S_)
        if m:
            arg = m.group(1)
            mm = re.fullmatch(r'"X" \+ VARPTR\$\((.*)\)', arg)     # PLAY "X"+VARPTR$(a$) = play a$
            return [f'await rt.play({E(mm.group(1)) if mm else E(arg)});']
        if u == 'RANDOMIZE TIMER': return ['rt.randomize(rt.TIMER());']
        m = re.fullmatch(r'READ (.*)', S_)
        if m: return [assign(m.group(1), f'rt.read({"true" if m.group(1).split("(")[0].endswith("$") else "false"})')]
        m = re.fullmatch(r'SWAP (.*)', S_)
        if m:
            a, b = [p.strip() for p, _ in split_top(m.group(1), ',')]
            ra, _ = lvalue(a); rb, _ = lvalue(b)
            return [f'{{ const t = {ra}; {ra} = {rb}; {rb} = t; }}']
        m = re.fullmatch(r'(.+?) = (.*)', S_)
        if m:
            return [assign(m.group(1), E(m.group(2)))]
        raise SyntaxError(f'{off:05X} unhandled: {S_}')

    def module_js(self):
        E, lvalue, opt = self.E, self.lvalue, self.opt
        body = self.text.split('```basic', 1)[1].split('```', 1)[0]
        lines = [l.rstrip() for l in body.splitlines() if l.strip()]
        items = []
        for l in lines:
            m = re.fullmatch(r'((?:L|SUB)_([0-9A-F]+)):', l)
            if m: items.append(('label', int(m.group(2), 16), m.group(1))); continue
            m = re.fullmatch(r'([0-9A-F]{5})  (.*)', l)
            if not m: raise SyntaxError(f'line: {l!r}')
            items.append(('stmt', int(m.group(1), 16), m.group(2)))
        labels = {o for k, o, _ in items if k == 'label'}

        # FOR/NEXT pairing (textual nesting by variable)
        stack, pair = [], {}
        for i, (k, o, s) in enumerate(items):
            if k != 'stmt': continue
            m = re.fullmatch(r'FOR (\S+) = .*', s)
            if m: stack.append((m.group(1), i)); continue
            m = re.fullmatch(r'NEXT (\S+)(?: STEP (.*))?', s)
            if m:
                while stack and stack[-1][0] != m.group(1):
                    stack.pop()
                if not stack: raise SyntaxError(f'NEXT without FOR at {o:05X}')
                v, fi = stack.pop()
                pair[fi] = (i, m.group(2)); pair[i] = (fi, m.group(2))

        ret_n = [0]
        def next_ret():
            ret_n[0] += 1; return 0x100000 + ret_n[0]     # synthetic return points (above every listing offset)

        out = []
        cur = {'i': 0}

        def for_(off, var, start, lim):
            i = cur['i']
            ni, step = pair[i]
            step_js = E(step) if step else '1'
            body_lbl = 0x200000 + off                     # synthetic loop-top label
            after = 0x300000 + items[ni][1]               # synthetic label after the NEXT
            lv, _ = lvalue(var)
            # empty delay loop (FOR, its own label, NEXT): CPU-speed delay -> engine time (SUB_1E4A only)
            if ni == i + 2 and items[i + 1][0] == 'label':
                return [f'await rt.delayLoop({E(start)}, {E(lim)}); {lv} = fr(Math.max({E(start)}, Math.floor({E(lim)}) + 1));',
                        f'pc = 0x{after:06X}; continue;']
            return [f'{lv} = fr({E(start)}); F[0x{off:05X}] = [fr({E(lim)}), fr({step_js})];',
                    f'if (F[0x{off:05X}][1] >= 0 ? {lv} > F[0x{off:05X}][0] : {lv} < F[0x{off:05X}][0]) {{ pc = 0x{after:06X}; continue; }}',
                    f'case 0x{body_lbl:06X}:']

        def next_(off, var):
            i = cur['i']
            fi, _ = pair[i]
            foff = items[fi][1]
            lv, _ = lvalue(var)
            after = 0x300000 + off
            if fi == i - 2 and items[i - 1][0] == 'label':
                return [f'case 0x{after:06X}:']
            return [f'{lv} = fr({lv} + F[0x{foff:05X}][1]);',
                    f'if (F[0x{foff:05X}][1] >= 0 ? {lv} <= F[0x{foff:05X}][0] : {lv} >= F[0x{foff:05X}][0]) {{ pc = 0x{0x200000 + foff:06X}; continue; }}',
                    f'case 0x{after:06X}:']

        inject = {int(k, 16): v for k, v in opt.get('inject_before', {}).items() if not k.startswith('_')}
        ctx = {'labels': labels, 'next_ret': next_ret, 'for': for_, 'next': next_}
        first = True
        for i, (k, o, s) in enumerate(items):
            cur['i'] = i
            if k == 'label':
                out.append(f'      case 0x{o:04X}: // {s}')
                continue
            if first:
                out.append(f'      case 0x{o:04X}: // module start'); first = False
            for l in inject.get(o, []):
                out.append('        ' + l)
            try:
                js = self.stmt(o, s, ctx)
            except SyntaxError as e:
                raise SystemExit(f'{o:05X}: {e}')
            out.append(f'        // {o:05X}  {s}')
            for j in js:
                if j.startswith('case '):
                    out.append('      ' + j)
                else:
                    out.append('        ' + j)
        FIRST = next(o for k, o, _ in items if k == 'stmt')
        prelude = ''.join('  %s\n' % l for l in opt.get('prelude', []))
        hdr = f'''// flow.js — GENERATED by {opt['tool_banner']} from decode/pseudo/{self.mod}.bas.md
// (+ {self.mod}_names.json). Do not edit by hand: fix the generator or the decode, then regenerate.
// Every BASIC statement is shown as `// <listing offset>  <statement>` above its JS translation.
// Runtime helpers (rt.*, cint, fr, B, AND, OR, NOT, ...) are in {opt['runtime_doc']}.
/* eslint-disable no-fallthrough, no-labels */
import {{ cint, fr, ix, B, AND, OR, NOT, MOD, IDIV, ASC, STR, VAL, LEFT, RIGHT, MID, STRING }} from '{opt['runtime']}';

export async function flow(rt) {{
  const {{ G, V, A, S, INFO }} = rt;
{prelude}  const gs = [];   // GOSUB return stack
  const F = {{}};    // FOR limit/step per FOR statement offset
  let pc = 0x{FIRST:04X};
  for (;;) {{
    if (rt.idle) await rt.yieldFrame();     // an empty INKEY$/TIMER poll -> let the browser run one frame
    else if (++rt.spin > 200000) await rt.yieldFrame();
    switch (pc) {{
'''
        ftr = f'''      default:
        throw new Error('{self.mod} flow: no label 0x' + pc.toString(16));
    }}
  }}
}}
'''
        self.stats = f'{len(items)} items, {len(labels)} labels, {ret_n[0]} return points'
        return hdr + '\n'.join(out) + '\n' + ftr


class _FlowP:
    """flow back end expressions. precedence: OR < AND < NOT < relational < +- < MOD < \\ < */ < unary- < ^"""
    def __init__(self, be, toks): self.be, self.t, self.i = be, toks, 0
    def peek(self, k=0): return self.t[self.i + k] if self.i + k < len(self.t) else (None, None)
    def take(self, val=None):
        tk = self.peek()
        if val is not None and tk[1] != val: raise SyntaxError(f'expected {val} got {tk} in {self.t}')
        self.i += 1; return tk
    def at(self, val): return self.peek()[1] == val
    def done(self): return self.i >= len(self.t)
    def expr(self): return self.p_or()
    def p_or(self):
        a = self.p_and()
        while self.at('OR'): self.take(); a = f'OR({a}, {self.p_and()})'
        return a
    def p_and(self):
        a = self.p_not()
        while self.at('AND'): self.take(); a = f'AND({a}, {self.p_not()})'
        return a
    def p_not(self):
        if self.at('NOT'): self.take(); return f'NOT({self.p_not()})'
        return self.p_rel()
    def p_rel(self):
        a = self.p_add()
        ops = {'=': '==', '<>': '!=', '<': '<', '>': '>', '<=': '<=', '>=': '>='}
        while self.peek()[1] in ops:
            op = ops[self.take()[1]]; b = self.p_add(); a = f'B({a} {op} {b})'
        return a
    def p_add(self):
        a = self.p_mod()
        while self.peek()[1] in ('+', '-'):
            op = self.take()[1]; a = f'({a} {op} {self.p_mod()})'
        return a
    def p_mod(self):
        a = self.p_idiv()
        while self.at('MOD'): self.take(); a = f'MOD({a}, {self.p_idiv()})'
        return a
    def p_idiv(self):
        a = self.p_mul()
        while self.at('\\'): self.take(); a = f'IDIV({a}, {self.p_mul()})'
        return a
    def p_mul(self):
        a = self.p_neg()
        while self.peek()[1] in ('*', '/'):
            op = self.take()[1]; a = f'({a} {op} {self.p_neg()})'
        return a
    def p_neg(self):
        if self.at('-'): self.take(); return f'(-{self.p_neg()})'
        if self.at('+'): self.take(); return self.p_neg()
        return self.p_pow()
    def p_pow(self):
        a = self.atom()
        while self.at('^'): self.take(); a = f'Math.pow({a}, {self.atom_neg()})'
        return a
    def atom_neg(self):
        if self.at('-'): self.take(); return f'(-{self.atom()})'
        return self.atom()
    def args(self):
        self.take('('); out = []
        if self.at(')'): self.take(); return out
        while True:
            out.append(self.expr())
            if self.at(','): self.take(); continue
            self.take(')'); return out
    def atom(self):
        be = self.be
        kind, v = self.take()
        if kind == 'num': return v
        if kind == 'str': return json.dumps(v[1:-1])
        if kind == 'op' and v == '(':
            e = self.expr(); self.take(')'); return f'({e})'
        if kind == 'id':
            up = v.upper()
            if up in be.NOARG: return be.NOARG[up]
            if v in be.FUNCS or up in be.FUNCS:
                a = self.args(); return be.func(v, a)
            if self.at('('):
                a = self.args(); return be.array_ref(v, a)
            return be.scalar_ref(v)
        raise SyntaxError(f'atom {kind} {v}')


