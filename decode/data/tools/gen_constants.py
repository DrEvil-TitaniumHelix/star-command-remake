"""gen_constants.py: build decode/data/MODULE_CONSTANTS.md from the _<MOD>.json files written by modconst.py --json.
--public writes decode/data/MODULE_CONSTANTS.public.md instead (BYOC, lane byoc-b3, Foreman decision for B4): the same
document without the game text - string literal and DATA texts become (load-module offset, length), unclassified INIT
bytes their length, and quoted game strings in the layout prose their DS offsets (tools/byoc/annot_audit.py locate()).
The importer reads the texts from the player's EXEs at those offsets."""
import json,os,sys
T='decode/data/tools'
PUB='--public' in sys.argv
if PUB:
    sys.path.insert(0,'tools/byoc')
    from annot_audit import locate, QUOTE
MODS=[('STARCOMM','STARCOMM.EXE'),('STARTUP','STARTUP.EXE'),('SPACE','SPACE.EXE'),('STARPORT','STARPORT.EXE'),('INSIDE','INSIDE.EXE'),('PLBATTLE','PLBATTLE.EXE'),('SPBATTLE','SPBATTLE.EXE'),
      ('SPACE_STR','SPACE.STR'),('STARPORT_STR','STARPORT.STR'),('INSIDE_STR','INSIDE.STR'),('PLBATTLE_STR','PLBATTLE.STR')]
def esc(t):
    o=''
    for c in t:
        if c=='|': o+='\\|'
        elif c=='`': o+="'"
        elif 32<=ord(c)<127: o+=c
        else: o+='\\x%02x'%ord(c)
    return o
out=[]
w=out.append
w('# Star Command module constant areas (string literals, numeric constants, DATA, line tables)\n')
w(('**Public variant** (no game text: texts are given as load-module offset + length; the importer reads them from the player\'s EXEs). Full version: MODULE_CONSTANTS.md (RE workspace only).\n\n' if PUB else '')+'Lane: data. Generated by `decode/data/tools/gen_constants.py` from `decode/data/tools/modconst.py --json` runs over the originals in `re-targets/starcommand/starcoma/` (read 2026-10-15). Regenerate: `python decode/data/tools/modconst.py <MOD>.EXE --json decode/data/tools/_<MOD>.json` then `python decode/data/tools/gen_constants.py`.\n')
lay=open(os.path.join(T,'layout_section.md'),encoding='utf-8').read()
if PUB:
    gs=[]
    for mod,fn in MODS:
        jj=json.load(open('%s/_%s.json'%(T,mod)))
        gs+=[(fn.replace('.EXE',''),'str',i['addr'],i['text']) for i in jj['init'] if i['kind']=='str' and i['text']]
        gs+=[(fn.replace('.EXE',''),'data',r['line'],r['text']) for r in jj.get('data',[]) if r.get('line') is not None]
    lay=QUOTE.sub(lambda m: locate(m.group(1),None,gs) or m.group(0),lay)
w(lay)
# COMMON arrays table (from STR stubs, identical across the four)
j=json.load(open(T+'/_SPACE_STR.json'))
w('## COMMON block arrays (from the STR stubs\' INIT records; identical in SPACE/STARPORT/INSIDE/PLBATTLE.STR)\n')
w('Each stub declares the same COMMON block as the main modules so CHAIN passes variables. These array descriptors therefore give the COMMON layout shared by every module (scalars in COMMON are not listed in INIT; the block spans DS 0x1850.. per hw[20]/hw[21]).\n')
w('| descriptor DS addr (SPACE.STR) | data DS addr | flags | bytes | count | elem size | evidence (SPACE.STR lm offset: record bytes) |')
w('|---|---|---|---|---|---|---|')
for it in j['init']:
    if it['kind']=='array':
        w('| 0x%04X | 0x%04X | 0x%04X | %d | %d | %d | 0x%X: `0e 00 %02x %02x %s` |'%(it['addr'],it['data'],it['flags'],it['bytes'],it['count'],it['bytes']//it['count'],it['off'],it['addr']&255,it['addr']>>8,it['raw']))
w('')
w('Note: `data 0x1850 flags 0x182 bytes 10404 count 2601` = the 51x51 single array that CHARINFO.BAS BSAVEs (file len 10404 = 0x28A4, BSAVE offset 0x1850). flags 0x184 = 1-dimensional, 0x182 = 2-dimensional (hypothesis from the two cases; element size is 4 in all). Descriptor addresses differ by module (the STR stub for SPACE places them at 0x48D8.., the main module may not), only the data addresses are shared.\n')
for mod,fn in MODS:
    j=json.load(open('%s/_%s.json'%(T,mod)))
    w('## %s  (source `%s`)\n'%(fn,j.get('source_name')))
    w('- load module: %d bytes; code 0x40..0x%X; DS constants/variables 0x%04X..0x%04X; COMMON 0x%04X + 0x%X bytes; header words: %s'%(j['lm_len'],j['code_end'],j['data_start'],j['data_end'],j['common_start'],j['common_len'],' '.join(j['header_words'])))
    w('- blocks (id/kind n len @lm offset): '+', '.join('0x%X/%s n=%d len=%d @0x%X'%(b['id'],b.get('kind'),b['n'],b['len'],b['off']) for b in j['blocks']))
    w('- block A data: `%s`; OFS: %s'%(j.get('blockA'),j.get('ofs')))
    d=j.get('data',[])
    w('\n### DATA statements (%d records)\n'%len(d))
    if d and PUB:
        hw=[int(x,16) for x in j['header_words']]; nm,it=hw[28]*16,hw[29]*16
        pos=[b['off'] for b in j['blocks'] if nm<b['off']<it][0]+16
        w('| line | text at lm | bytes |'); w('|---|---|---|')
        for r in d:
            n=len(r['text'].split()) if r['line'] is None else len(r['text'].encode('latin1'))
            w('| %s | 0x%X | %d |'%(r['line'] if r['line'] is not None else 'end (FF FF)',pos+2,n)); pos+=2+n+1
    elif d:
        w('| line | text |'); w('|---|---|')
        for r in d:
            w('| %s | `%s` |'%(r['line'] if r['line'] is not None else 'end (FF FF)',esc(r['text'])))
    strs=[i for i in j['init'] if i['kind']=='str']; nums=[i for i in j['init'] if i['kind'] in ('single','double','int')]; arrs=[i for i in j['init'] if i['kind']=='array']; raws=[i for i in j['init'] if i['kind']=='raw']
    w('\n### String literals (%d) - `mov bx,<desc>` in the listing = this literal\n'%len(strs))
    w('| desc DS | body DS | len | text | %s | lm off |'%('pad bytes' if PUB else 'pad')); w('|---|---|---|---|---|---|')
    for s in strs:
        if PUB: w('| 0x%04X | 0x%04X | %d | %s | %s | 0x%X |'%(s['addr'],s['body_addr'],s['len'],('text at lm 0x%X'%(s['off']+12)) if s['len'] else '',len(s['pad'])//2,s['off']))
        else: w('| 0x%04X | 0x%04X | %d | `%s` | %s | 0x%X |'%(s['addr'],s['body_addr'],s['len'],esc(s['text']) if s['text'] else '',s['pad'],s['off']))
    w('\n### Numeric constants (%d, MBF single unless noted)\n'%len(nums))
    w('| DS addr | bytes | value | lm off |'); w('|---|---|---|---|')
    for n in nums: w('| 0x%04X | `%s` | %s%s | 0x%X |'%(n['addr'],n['bytes'],('%g'%n['value']),'' if n['kind']=='single' else ' ('+n['kind']+')',n['off']))
    if arrs:
        w('\n### Array descriptors (%d)\n'%len(arrs)); w('| desc DS | data DS | flags | bytes | count |'); w('|---|---|---|---|---|')
        for a in arrs: w('| 0x%04X | 0x%04X | 0x%04X | %d | %d |'%(a['addr'],a['data'],a['flags'],a['bytes'],a['count']))
    if raws:
        w('\n### Unclassified INIT records (%d)\n'%len(raws))
        for r in raws: w(('- 0x%04X: %d bytes'%(r['addr'],len(r['bytes'].split()))) if PUB else ('- 0x%04X: `%s`'%(r['addr'],r['bytes'])))
    L=j.get('lines',[])
    w('\n### Line-number table (%d entries; shown as listingAddr:line)\n'%len(L))
    if L:
        toks=['%05X:%d'%(o+0x10,l) for o,l in L]
        for i in range(0,len(toks),12): w('    '+'  '.join(toks[i:i+12]))
    w('')
open('decode/data/MODULE_CONSTANTS.public.md' if PUB else 'decode/data/MODULE_CONSTANTS.md','w',encoding='utf-8').write('\n'.join(out))
print('wrote',len(out),'lines')
