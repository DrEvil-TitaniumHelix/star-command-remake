import { qbdis } from './qbdis.js';
import { parse as modconst } from './modconst.js';
import { qb2basTwoPass } from './qb2bas.js';
import { bas2js, moduleOptions } from './bas2js.js';
import { loads, dumps } from './py.js';

const univ = (s) => s.replace(/\r\n?/g, '\n');

export function qb2basOptions(args = []) {
  const o = {};
  for (let i = 0; i < args.length; i += 2) {
    if (args[i] === '--tempbase') o.tempbase = parseInt(args[i + 1], 16);
    else if (args[i] === '--end') o.end = parseInt(args[i + 1], 16);
    else throw new Error('qb2bas option ' + args[i]);
  }
  return o;
}

const shift = (segs, a) => a + (segs?.findLast(([f]) => a >= parseInt(f, 16))?.[1] ?? 0);
const unshift = (segs, v) => { for (const [, d] of segs ?? []) if (shift(segs, v - d) === v) return v - d; return v; };

export function stringTableJs(cfg, files, vers) {
  const { out, modules } = cfg.strings;
  const lines = [`// ${out.split('/').pop()} — GENERATED by game/byoc/pipeline.js stringTableJs() from the string-literal INIT tables of`,
    `// ${modules.map((m) => m + '.EXE').join(', ')} (MODULE_CONSTANTS.public.md): DS address of the descriptor -> text. Do not edit by hand;`,
    '// the BYOC importer writes this file from the player\'s EXEs, game/modules/startup.js reads every game string from it.'];
  for (const mod of modules) {
    const c = modconst(files.get(mod + '.EXE'), mod + '.EXE'), segs = cfg.modules[mod].variants?.[vers?.get(mod + '.EXE')]?.data;
    lines.push(`export const ${mod} = {`);
    for (const it of c.init) if (it.kind === 'str') lines.push(`  0x${unshift(segs, it.addr).toString(16).toUpperCase().padStart(4, '0')}: ${dumps(it.text)},`);
    lines.push('};');
  }
  return { path: out, js: lines.join('\n') + '\n' };
}

export function buildModule(mod, { exe, files = new Map(), cfg, rtNames, inlineArgs, names, header, sprites = '', variant }) {
  const mc = cfg.modules[mod];
  if (!mc) throw new Error('unknown module ' + mod);
  const listing = qbdis(exe, rtNames, inlineArgs);
  const consts = modconst(exe, mod + '.EXE');
  const out = { listing, consts, basmd: null, js: null, banks: null };
  if (!mc.qb2bas) return out;
  const code = mc.variants?.[variant]?.code, qo = qb2basOptions(mc.qb2bas);
  let nm = loads(names);
  if (code) {
    nm = new Map([...nm].map(([k, v]) => [k.replace(/^(SUB|FN)([0-9A-F]{4})/, (_, p, a) => p + shift(code, parseInt(a, 16)).toString(16).toUpperCase().padStart(4, '0')), v]));
    if (qo.end !== undefined) qo.end = shift(code, qo.end);
  }
  out.basmd = qb2basTwoPass(listing, consts, nm, { title: mod, header: univ(header), ...qo });
  if (!mc.bas2js) return out;
  const r = bas2js(mod, moduleOptions(cfg, mod), univ(out.basmd), nm, consts, { sprites: univ(sprites), files });
  out.js = r.js; out.banks = r.banks;
  return out;
}
