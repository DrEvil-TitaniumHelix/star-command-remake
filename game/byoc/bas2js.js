class FlowP {
  constructor(be, toks) { this.be = be; this.t = toks; this.i = 0; }
  peek(k = 0) { return this.i + k < this.t.length ? this.t[this.i + k] : [null, null]; }
  take(val) {
    const tk = this.peek();
    if (val !== undefined && tk[1] !== val) throw new SyntaxError(`expected ${val} got ${tk}`);
    this.i++; return tk;
  }
  at(v) { return this.peek()[1] === v; }
  done() { return this.i >= this.t.length; }
  expr() { return this.pOr(); }
  pOr() { let a = this.pAnd(); while (this.at('OR')) { this.take(); a = `OR(${a}, ${this.pAnd()})`; } return a; }
  pAnd() { let a = this.pNot(); while (this.at('AND')) { this.take(); a = `AND(${a}, ${this.pNot()})`; } return a; }
  pNot() { if (this.at('NOT')) { this.take(); return `NOT(${this.pNot()})`; } return this.pRel(); }
  pRel() {
    let a = this.pAdd();
    const ops = { '=': '==', '<>': '!=', '<': '<', '>': '>', '<=': '<=', '>=': '>=' };
    while (Object.hasOwn(ops, this.peek()[1] ?? '')) { const op = ops[this.take()[1]]; const b = this.pAdd(); a = `B(${a} ${op} ${b})`; }
    return a;
  }
  isStr(i) { let t = this.t[i]; while (t && t[1] === '(') t = this.t[++i]; return !!t && (t[0] === 'str' || (t[0] === 'id' && t[1].endsWith('$'))); }
  pAdd() { const s = this.isStr(this.i); let a = this.pMod(); while (this.peek()[1] === '+' || this.peek()[1] === '-') { const op = this.take()[1]; a = s ? `(${a} ${op} ${this.pMod()})` : `fr(${a} ${op} ${this.pMod()})`; } return a; }
  pMod() { let a = this.pIdiv(); while (this.at('MOD')) { this.take(); a = `MOD(${a}, ${this.pIdiv()})`; } return a; }
  pIdiv() { let a = this.pMul(); while (this.at('\\')) { this.take(); a = `IDIV(${a}, ${this.pMul()})`; } return a; }
  pMul() { let a = this.pNeg(); while (this.peek()[1] === '*' || this.peek()[1] === '/') { const op = this.take()[1]; a = `fr(${a} ${op} ${this.pNeg()})`; } return a; }
  pNeg() {
    if (this.at('-')) { this.take(); return `(-${this.pNeg()})`; }
    if (this.at('+')) { this.take(); return this.pNeg(); }
    return this.pPow();
  }
  pPow() { let a = this.atom(); while (this.at('^')) { this.take(); a = `fr(Math.pow(${a}, ${this.atomNeg()}))`; } return a; }
  atomNeg() { if (this.at('-')) { this.take(); return `(-${this.atom()})`; } return this.atom(); }
  args() {
    this.take('('); const out = [];
    if (this.at(')')) { this.take(); return out; }
    for (;;) {
      out.push(this.expr());
      if (this.at(',')) { this.take(); continue; }
      this.take(')'); return out;
    }
  }
  atom() {
    const be = this.be, C = FlowBackend;
    const [kind, v] = this.take();
    if (kind === 'num') return lit(v);
    if (kind === 'str') return jsq(v.slice(1, -1));
    if (kind === 'op' && v === '(') { const e = this.expr(); this.take(')'); return `(${e})`; }
    if (kind === 'id') {
      const up = v.toUpperCase();
      if (Object.hasOwn(C.NOARG, up)) return C.NOARG[up];
      if (C.FUNCS.has(v) || C.FUNCS.has(up)) return be.func(v, this.args());
      if (this.at('(')) return be.arrayRef(v, this.args());
      return be.scalarRef(v);
    }
    throw new SyntaxError(`atom ${kind} ${v}`);
  }
}

export function bas2js(mod, opt, text, names, consts, { sprites = '', files = new Map() } = {}) {
  if (opt.backend === 'flow') {
    const be = new FlowBackend(mod, opt, text, names);
    const js = be.moduleJs();
    return { js, banks: null, log: [be.stats] };
  }
  const be = new ClassBackend(mod, opt, text, names, consts, files);
  const data = dataItems(consts);
  const js = be.moduleJs(data);
  const banks = bankOffsets(sprites);
  const log = [fmt('DATA items %d ; banks %d ; BLOAD regions %s', data.length, banks.size, JSON.stringify(Object.fromEntries([...be.regions].map(([b, l]) => [fmt('%04X', b), l])))),
    fmt('%d statements; %d untranslated', be.stmts.length, be.problems.length),
    ...be.problems.slice(0, 60).map((p) => fmt('  %05X line %d: %s  <- %s', ...p))];
  return { js, banks: banksJs(banks, opt.tool_banner), log };
}

export function moduleOptions(cfg, mod) {
  const mc = cfg.modules[mod].bas2js;
  return { ...cfg.bas2js_defaults[mc.backend], ...mc };
}
