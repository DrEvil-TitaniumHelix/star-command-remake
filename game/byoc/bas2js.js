    const isS = (x) => strip(x).split('(')[0].endsWith('$');
    m = /^INPUT #(\d+), (.*)$/.exec(t);
    if (m) return splitTop(m[2]).map(([x]) => assign(x, fmt('this.inputField(%s, %s)', m[1], isS(x) ? 'true' : 'false'))).join(' ');
