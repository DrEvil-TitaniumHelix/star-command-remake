      w(Cls + '.COMMON_VARS = ' + dumps(new Map(sortedNames.filter(([, i]) => i[0] === 's' && ClassBackend.STR_HI <= i[1] && i[1] < commonEnd).map(([n, i]) => [n, i[1]])), { sep: ',', kv: ':' }) + ';');
      w('');
