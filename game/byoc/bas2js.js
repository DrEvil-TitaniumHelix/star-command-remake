    w('    }');
    w('  }');
    w('}');
    w('');
    w('export const DATA = ' + dumps(data) + ';');
    const sortedNames = [...this.byName.entries()].sort((p, q) => (p[0] < q[0] ? -1 : p[0] > q[0] ? 1 : 0));
