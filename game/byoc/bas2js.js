import { fmt, strip, rstrip, lstrip, split, dumps } from './py.js';

const W = '[\\p{L}\\p{N}_]';
const re = (s, f = '') => new RegExp(s, 'u' + f);
const m_ = (r, s) => r.exec(s);
const reEsc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

export function splitTop(s, seps = [',']) {
  const out = []; let depth = 0, q = false, cur = '';
  for (const ch of s) {
    if (ch === '"') q = !q;
    if (!q) {
      if (ch === '(') depth++;
      else if (ch === ')') depth--;
      else if (depth === 0 && seps.includes(ch)) { out.push([cur, ch]); cur = ''; continue; }
    }
    cur += ch;
  }
  out.push([cur, null]);
  return out;
}

function splitlines(s) {
  const out = s.split(/\r\n|[\n\r\x0b\x0c\x1c\x1d\x1e\x85\u2028\u2029]/);
  if (out.length && out[out.length - 1] === '') out.pop();
  return out;
}

export function dataItems(consts) {
  const items = [];
  for (const r of consts.data || []) {
    if (r.line === null || r.line === undefined) continue;
    for (const [item] of splitTop(r.text)) {
      const it = strip(item);
      items.push(it.startsWith('"') && it.endsWith('"') ? it.slice(1, -1) : it);
    }
  }
  return items;
}

export function bankOffsets(tsv) {
  const banks = new Map();
  for (const row of tsv.split('\n')) {
    const c = rstrip(row, '\r\n').split('\t');
    if (c.length < 7) continue;
    banks.set(c[0], [...c[6].matchAll(/\d+:\d+x\d+@(\d+)/g)].map((m) => parseInt(m[1], 10)));
  }
  return banks;
}

export function banksJs(banks, toolBanner) {
  return fmt('// banks.js — GENERATED by %s from decode/data/sprites_index.tsv:\n', toolBanner) +
    '// file offsets of the GET arrays in each sprite bank (index = position), used to PUT by DS address.\n' +
    'export const BANK_OFFSETS = ' + dumps(banks, { sep: ',', kv: ':' }) + ';\n';
}

function globFiles(files, pat) {
  const r = new RegExp('^' + pat.split('*').map(reEsc).join('.*') + '$', 'i');
  return [...files.keys()].filter((n) => r.test(n)).sort();
}

function bsaveLengths(stmts, files) {
  const regions = new Map();
  for (const [, , t] of stmts) {
    const m = /^BLOAD (.*), &H([0-9A-F]+)$/.exec(t);
    if (!m) continue;
    const base = parseInt(m[2], 16);
    const lits = [...m[1].matchAll(/"([^"]*)"/g)].map((x) => x[1]).filter((x) => x !== 'A:' && x !== 'B:');
    const stem = lits.length ? lits[0].toUpperCase() : '';
    const ext = lits.length > 1 && lits[lits.length - 1].startsWith('.') ? lits[lits.length - 1].toUpperCase() : (stem.includes('.') ? '' : '.BAS');
    const pat = m[1].includes('STR$') ? stem + '*' + ext : stem + ext;
    let ln = 0;
    for (const f of globFiles(files, pat)) {
      const b = files.get(f);
      if (b[0] === 0xfd) ln = Math.max(ln, b[5] | (b[6] << 8));
    }
    regions.set(base, Math.max(regions.has(base) ? regions.get(base) : 0, ln));
  }
  return regions;
}

